#!/usr/bin/env python3
"""Summarise the per-length `tilefoundry analyze` reports of one version.

Reads reports/analyze/<V>/T<T>/<selection>.{json,txt} (written by
tools/analyze_all.sh) and writes reports/analyze/<V>/SUMMARY.md:

  1. per selection and length: flops by dtype, gmem bytes, roofline compute /
     memory / ideal ns and the bound, the unscheduled performance prediction;
  2. the prefill composed from its parts (48 GDN layers + 16 attention layers +
     embed + final norm + head), next to the hand ledger (FLOPS.md);
  3. per call kind (matmul by weight, delta-rule core, attention core, norms,
     elementwise ...): summed roofline ideal ns and which side bounds it.
"""
from __future__ import annotations

import json
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LENGTHS = (128, 256, 512, 1024)
SELECTIONS = ("layer0", "layer3", "embed", "final_norm", "lm_head")
COUNT = {"layer0": 48, "layer3": 16, "embed": 1, "final_norm": 1, "lm_head": 1}
CALL = re.compile(r"^\s*(\S+) = (tf\.\w+|\w+)\((.*?)\)\s+# (.*)$")


def kind_of(op: str, args: str) -> str:
    if op == "tf.matmul":
        for w in ("w_qkv", "w_z", "w_b", "w_a", "w_out", "w_gate", "w_up", "w_down", "w_q", "w_k", "w_v", "w_o", "w_head"):
            if re.search(rf"\b{w}\b", args):
                return f"matmul {w}"
        return "matmul (activation x activation)"
    return op


def per_call(txt: Path):
    rows = defaultdict(lambda: [0, 0, 0, 0, set()])  # ideal, compute, memory, count, bounds
    definitions = 0
    for line in txt.read_text().splitlines():
        if line.startswith("def "):
            definitions += 1
            if definitions > 1:
                break
        m = CALL.match(line)
        if not m:
            continue
        name, op, args, ann = m.groups()
        r = re.search(r"roofline ideal-ns=(\d+) bound-by=(\w+)", ann)
        if not r:
            continue
        k = kind_of(op, args)
        rows[k][0] += int(r.group(1))
        rows[k][3] += 1
        rows[k][4].add(r.group(2))
    return rows


def main(version: str) -> None:
    base = ROOT / "reports/analyze" / version
    ledger = json.loads((ROOT / "reports/flops.json").read_text())["rows"]
    md = [f"# analyze summary, version `{version}`", "",
          "Generated by `tools/analyze_summary.py` from `tools/analyze_all.sh` output "
          "(`tilefoundry analyze <src>:<Module>.<function> --compute-cost --memory --roofline --performance --dim seq_len=T`).",
          "", "## 1. Per selection", "",
          "| T | selection | x | bf16 GFLOP | f32 GFLOP | gmem read GB | gmem write GB | compute us | memory us | ideal us | bound | unscheduled perf us |",
          "|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|---|---:|"]
    composed = {}
    for T in LENGTHS:
        tot = defaultdict(float)
        for sel in SELECTIONS:
            d = json.loads((base / f"T{T}/{sel}.json").read_text())
            d = d["functions"][0]
            fr = d["function_records"]
            fl = d["totals"]["flops"]
            gm = d["totals"]["traffic"].get("gmem", {"read": 0, "write": 0})
            rf = fr["roofline"]
            perf = fr["performance"]["timeline"]["end_ns"]
            n = COUNT[sel]
            md.append(f"| {T} | {sel} | {n} | {fl.get('bf16', 0)/1e9:.2f} | {fl.get('f32', 0)/1e9:.3f} | "
                      f"{gm['read']/1e9:.3f} | {gm['write']/1e9:.3f} | {rf['compute_ns']/1e3:.1f} | {rf['memory_ns']/1e3:.1f} | "
                      f"{rf['ideal_ns']/1e3:.1f} | {rf['bound_by']} | {perf/1e3:.0f} |")
            tot["bf16"] += n * fl.get("bf16", 0)
            tot["f32"] += n * fl.get("f32", 0)
            tot["bytes"] += n * (gm["read"] + gm["write"])
            tot["compute_ns"] += n * rf["compute_ns"]
            tot["memory_ns"] += n * rf["memory_ns"]
            tot["ideal_sum_ns"] += n * rf["ideal_ns"]
            tot["perf_ns"] += n * perf
        composed[T] = tot
    md += ["", "## 2. The prefill composed from its parts, next to the hand ledger", "",
           "`ideal (sum of parts)` adds each part's own max(compute, memory): the parts run one after another. "
           "`ideal (whole)` is max(summed compute, summed memory), analyze's own rule for one Function.",
           "", "| T | analyze bf16 GFLOP | analyze f32 GFLOP | ledger GFLOP | analyze gmem GB (unfused) | ledger compulsory GB | "
           "analyze ideal (sum of parts) ms | analyze ideal (whole) ms | ledger roofline ms | analyze unscheduled perf ms |",
           "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for T, row in zip(LENGTHS, ledger):
        t = composed[T]
        whole = max(t["compute_ns"], t["memory_ns"])
        md.append(f"| {T} | {t['bf16']/1e9:,.1f} | {t['f32']/1e9:,.1f} | {row['total_flops']/1e9:,.1f} | {t['bytes']/1e9:.1f} | "
                  f"{row['total_bytes']/1e9:.1f} | {t['ideal_sum_ns']/1e6:.3f} | {whole/1e6:.3f} | {row['roofline_ms']:.3f} | {t['perf_ns']/1e6:.0f} |")
    md += ["", "## 3. Where the parts' ideal time goes (per call kind, one layer)", "",
           "Direct calls in the selected entry only; retained callees are counted at their call sites, "
           "without counting their bodies a second time.", ""]
    for sel in ("layer0", "layer3"):
        md += [f"### {sel} ({'GDN' if sel == 'layer0' else 'attention'} layer)", "",
               "| call kind | calls | " + " | ".join(f"T={T} ideal us (bound)" for T in LENGTHS) + " |",
               "|---|---:|" + "---:|" * len(LENGTHS)]
        per_t = {T: per_call(base / f"T{T}/{sel}.txt") for T in LENGTHS}
        kinds = sorted(per_t[1024], key=lambda k: -per_t[1024][k][0])
        for k in kinds:
            cells = []
            for T in LENGTHS:
                r = per_t[T].get(k)
                cells.append(f"{r[0]/1e3:.1f} ({'/'.join(sorted(r[4]))})" if r else "-")
            md.append(f"| {k} | {per_t[1024][k][3]} | " + " | ".join(cells) + " |")
        md.append("")
    out = base / "SUMMARY.md"
    out.write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "v0")
