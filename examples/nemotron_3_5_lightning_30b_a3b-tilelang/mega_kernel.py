@tilelang.jit
def build_attn(arm):
    @T.prim_func
    def attn(
        qg: T.Tensor((QP,), "bfloat16"),
        ptrs: T.Tensor((NPTR,), "int64"),
        meta: T.Tensor((2,), "int32"),
        scratch: T.Tensor((SCRATCH,), "float32"),
        out: T.Tensor((QP,), "bfloat16"),
    ):
        with T.Kernel(NHEAD, NW, threads=THREADS) as (bx, by):
            ks = T.alloc_shared((ABLK, DH), "bfloat16")
            vs = T.alloc_shared((ABLK, DH), "bfloat16")
            ps = T.alloc_shared((GQA, ABLK), "bfloat16")
            fs2 = T.alloc_shared((FROW, DH), "float32")
            T.annotate_layout({fs2: T.Layout((FROW, DH), lambda i, j: i * DH + j)})
            fs = T.view(fs2, (FARENA,))
            red = T.alloc_shared((THREADS,), "float32")
            sml = T.alloc_shared((4 * HQ + 4,), "float32")
            acc = T.alloc_local((1,), "float32")
            av = T.alloc_local((16,), "float32")
            fv = T.alloc_local((4,), "float32")
            iv = T.alloc_local((4,), "int32")
            of0 = T.alloc_fragment((GQA, DH), "float32")
            of1 = T.alloc_fragment((GQA, DH), "float32")
            sfg = T.alloc_fragment((GQA, ABLK), "float32")
            qf0 = T.alloc_fragment((GQA, DH), "bfloat16")
            qf1 = T.alloc_fragment((GQA, DH), "bfloat16")
            if arm == "head":
                cta = bx + by * 33
                tid = T.get_thread_binding()
                warp = tid // 32
                lane = tid % 32
                at = 0
                ctx_full = meta[0]
                ctx_tail = meta[1]
                ctx_all = ctx_full + ctx_tail
                _cfb = T.ceildiv(ctx_full, 128)
                for _i in T.unroll(16):
                    _j = _i * 256 + tid
                    fs[_j] = T.Cast("float32", qg[_j]) * QSCALE
                T.sync_threads()
                # ---- a head per bx, a quarter of the context per by
                _nb = T.if_then_else(bx < 32, T.ceildiv(T.max(T.ceildiv(ctx_all, 128) - by, 0), NW), 0)
                _grp = (bx // 16) * 128
                if tid == 0:
                    sml[129] = NEG
                    sml[130] = 0.0
                av[0] = 0.0
                T.sync_threads()
                for _b in T.serial(_nb):
                    _bi = by + _b * NW
                    iv[0] = T.max(T.min(ctx_all - _bi * 128, 128), 0)
                    _shk = T.make_tensor_from_addr(T.if_then_else(_bi < _cfb, ptrs[P_KC + at], ptrs[P_KT + at]), (CBLK, 128, 256), "bfloat16")
                    _ihk = T.max(T.min(T.if_then_else(_bi < _cfb, _bi, _bi - _cfb), 4095), 0)
                    T.copy(_shk[_ihk, :, _grp:_grp + 128], ks, prefer_instruction="cp_async")
                    _shv = T.make_tensor_from_addr(T.if_then_else(_bi < _cfb, ptrs[P_VC + at], ptrs[P_VT + at]), (CBLK, 128, 256), "bfloat16")
                    _ihv = T.max(T.min(T.if_then_else(_bi < _cfb, _bi, _bi - _cfb), 4095), 0)
                    T.copy(_shv[_ihv, :, _grp:_grp + 128], vs, prefer_instruction="cp_async")
                    T.sync_threads()
                    # scores: thread t owns position t % 128 and half of this head's dimensions
                    acc[0] = 0.0
                    fv[0] = 0.0
                    fv[1] = 0.0
                    fv[2] = 0.0
                    for _d in T.serial(16):
                        acc[0] += fs[bx * 128 + (tid // 128) * 64 + _d * 4 + 0] * T.Cast("float32", ks[tid % 128, (tid // 128) * 64 + _d * 4 + 0])
                        fv[0] += fs[bx * 128 + (tid // 128) * 64 + _d * 4 + 1] * T.Cast("float32", ks[tid % 128, (tid // 128) * 64 + _d * 4 + 1])
                        fv[1] += fs[bx * 128 + (tid // 128) * 64 + _d * 4 + 2] * T.Cast("float32", ks[tid % 128, (tid // 128) * 64 + _d * 4 + 2])
                        fv[2] += fs[bx * 128 + (tid // 128) * 64 + _d * 4 + 3] * T.Cast("float32", ks[tid % 128, (tid // 128) * 64 + _d * 4 + 3])
                    red[tid] = acc[0] + fv[0] + fv[1] + fv[2]
                    T.sync_threads()
                    if tid < 128:
                        fs[4096 + tid] = T.if_then_else(tid < iv[0], bf(red[tid] + red[128 + tid]), NEG)
                    T.sync_threads()
                    # this head's 128 scores: a quarter each to 32 threads, then one thread
                    if tid < 32:
                        red[tid] = T.max(T.max(fs[4096 + tid], fs[4096 + 32 + tid]), T.max(fs[4096 + 64 + tid], fs[4096 + 96 + tid]))
                    T.sync_threads()
                    if tid == 0:
                        acc[0] = NEG
                        for _u in T.unroll(32):
                            acc[0] = T.max(acc[0], red[_u])
                        fv[0] = T.max(sml[129], acc[0])
                        sml[131] = T.exp(sml[129] - fv[0])
                        sml[129] = fv[0]
                    T.sync_threads()
                    if tid < 128:
                        fs[4096 + tid] = T.exp(fs[4096 + tid] - sml[129])
                        red[tid] = fs[4096 + tid]
                    T.sync_threads()
                    if tid == 0:
                        acc[0] = 0.0
                        for _u in T.unroll(128):
                            acc[0] += red[_u]
                        sml[130] = sml[130] * sml[131] + acc[0]
                    T.sync_threads()
                    # accumulate: thread t owns dimension t % 128 and half of the positions
                    av[0] = av[0] * sml[131]
                    for _p in T.unroll(64):
                        if (tid // 128) * 64 + _p < iv[0]:
                            av[0] += fs[4096 + (tid // 128) * 64 + _p] * T.Cast("float32", vs[(tid // 128) * 64 + _p, tid % 128])
                    T.sync_threads()
                # this worker's partial for this head, for the four-way merge
                red[tid] = av[0]
                T.sync_threads()
                if tid < 128:
                    scratch[S_ATT + (by * NHEAD + bx) * 130 + tid] = red[tid] + red[128 + tid]
                if tid == 0:
                    scratch[S_ATT + (by * NHEAD + bx) * 130 + 128] = sml[129]
                    scratch[S_ATT + (by * NHEAD + bx) * 130 + 129] = sml[130]
                T.sync_grid()
                # merge the four workers of one head; only the first row of the grid does it
                if by == 0:
                    if tid == 0:
                        acc[0] = NEG
                        for _c in T.serial(NW):
                            acc[0] = T.max(acc[0], scratch[S_ATT + (_c * NHEAD + bx) * 130 + 128])
                        sml[MAXSLOT] = acc[0]
                    T.sync_threads()
                    if tid < 129:
                        acc[0] = 0.0
                        for _c in T.serial(NW):
                            acc[0] += T.exp(scratch[S_ATT + (_c * NHEAD + bx) * 130 + 128] - sml[MAXSLOT]) * scratch[S_ATT + (_c * NHEAD + bx) * 130 + T.if_then_else(tid < 128, tid, 129)]
                        red[tid] = acc[0]
                    T.sync_threads()
                    if tid < 128:
                        scratch[S_CTX + bx * 128 + tid] = bf(red[tid] / red[128])
                T.sync_grid()
                for _i in T.unroll(16):
                    _j = _i * 256 + tid
                    out[_j] = bf(scratch[S_CTX + _j])
            else:
                cta = bx + by * 33
                tid = T.get_thread_binding()
                warp = tid // 32
                lane = tid % 32
                at = 0
                ctx_full = meta[0]
                ctx_tail = meta[1]
                ctx_all = ctx_full + ctx_tail
                _cfb = T.ceildiv(ctx_full, 128)
                for _i in T.unroll(16):
                    _j = _i * 256 + tid
                    fs[_j] = T.Cast("float32", qg[_j]) * QSCALE
                T.sync_threads()
                # ---- a stripe of the context per CTA, both KV heads, ABLK at a time
                _tot = T.ceildiv(ctx_all, 128)
                _cb = T.ceildiv(_tot, 132)
                _b0 = cta * _cb
                _nblk = T.max(T.min(_cb, _tot - _b0), 0)
                # Q is already scaled in `fs`, one head to a row; the tensor cores want it
                # in bf16, and it fits in registers.
                T.copy(fs2[0:16, :], qf0)
                T.copy(fs2[16:32, :], qf1)
                if tid < 32:
                    sml[tid] = NEG
                    sml[32 + tid] = 0.0
                T.clear(of0)
                T.clear(of1)
                T.sync_threads()
                for _b in T.serial(_nblk):
                    _bi = _b0 + _b
                    iv[0] = T.max(T.min(ctx_all - _bi * 128, 128), 0)
                    # ---- KV group 0
                    _sk0 = T.make_tensor_from_addr(T.if_then_else(_bi < _cfb, ptrs[P_KC + at], ptrs[P_KT + at]), (CBLK, 128, 256), "bfloat16")
                    _ik0 = T.max(T.min(T.if_then_else(_bi < _cfb, _bi, _bi - _cfb), 4095), 0)
                    T.copy(_sk0[_ik0, :, 0:0 + 128], ks, prefer_instruction="cp_async")
                    _sv0 = T.make_tensor_from_addr(T.if_then_else(_bi < _cfb, ptrs[P_VC + at], ptrs[P_VT + at]), (CBLK, 128, 256), "bfloat16")
                    _iv0 = T.max(T.min(T.if_then_else(_bi < _cfb, _bi, _bi - _cfb), 4095), 0)
                    T.copy(_sv0[_iv0, :, 0:0 + 128], vs, prefer_instruction="cp_async")
                    T.sync_threads()
                    T.clear(sfg)
                    T.gemm(qf0, ks, sfg, transpose_B=True)
                    T.copy(sfg, ps)
                    T.sync_threads()
                    # The online softmax, in place over the score block: a head to sixteen
                    # threads and eight positions each. Those sixteen are sixteen adjacent
                    # lanes of one warp, so both reductions are butterflies over registers
                    # -- no shared round trip, no barrier, and the 240 threads a sixteen-
                    # wide serial fold would have left idle keep their own heads.
                    acc[0] = NEG
                    for _u in T.unroll(8):
                        if (tid % 16) * 8 + _u < iv[0]:
                            acc[0] = T.max(acc[0], T.Cast("float32", ps[tid // 16, (tid % 16) * 8 + _u]))
                    for _d in T.unroll(4):
                        acc[0] = T.max(acc[0], T.shfl_xor(acc[0], T.shift_left(1, _d)))
                    fv[0] = T.max(sml[0 + tid // 16], acc[0])
                    fv[2] = T.exp(sml[0 + tid // 16] - fv[0])
                    # a position past the end of the context gets a zero, which keeps it
                    # out of the sum and out of the product that follows
                    acc[0] = 0.0
                    for _u in T.unroll(8):
                        fv[1] = T.if_then_else((tid % 16) * 8 + _u < iv[0], T.exp(T.Cast("float32", ps[tid // 16, (tid % 16) * 8 + _u]) - fv[0]), 0.0)
                        ps[tid // 16, (tid % 16) * 8 + _u] = bf(fv[1])
                        acc[0] += fv[1]
                    for _d in T.unroll(4):
                        acc[0] += T.shfl_xor(acc[0], T.shift_left(1, _d))
                    if tid % 16 == 0:
                        sml[32 + tid // 16] = sml[32 + tid // 16] * fv[2] + acc[0]
                        sml[0 + tid // 16] = fv[0]
                        sml[96 + tid // 16] = fv[2]
                    T.sync_threads()
                    # rescale what the earlier blocks left, then add this block's share
                    for _i, _j in T.Parallel(16, 128):
                        of0[_i, _j] = of0[_i, _j] * sml[96 + _i]
                    T.gemm(ps, vs, of0)
                    # ---- KV group 1
                    _sk1 = T.make_tensor_from_addr(T.if_then_else(_bi < _cfb, ptrs[P_KC + at], ptrs[P_KT + at]), (CBLK, 128, 256), "bfloat16")
                    _ik1 = T.max(T.min(T.if_then_else(_bi < _cfb, _bi, _bi - _cfb), 4095), 0)
                    T.copy(_sk1[_ik1, :, 128:128 + 128], ks, prefer_instruction="cp_async")
                    _sv1 = T.make_tensor_from_addr(T.if_then_else(_bi < _cfb, ptrs[P_VC + at], ptrs[P_VT + at]), (CBLK, 128, 256), "bfloat16")
                    _iv1 = T.max(T.min(T.if_then_else(_bi < _cfb, _bi, _bi - _cfb), 4095), 0)
                    T.copy(_sv1[_iv1, :, 128:128 + 128], vs, prefer_instruction="cp_async")
                    T.sync_threads()
                    T.clear(sfg)
                    T.gemm(qf1, ks, sfg, transpose_B=True)
                    T.copy(sfg, ps)
                    T.sync_threads()
                    # The online softmax, in place over the score block: a head to sixteen
                    # threads and eight positions each. Those sixteen are sixteen adjacent
                    # lanes of one warp, so both reductions are butterflies over registers
                    # -- no shared round trip, no barrier, and the 240 threads a sixteen-
                    # wide serial fold would have left idle keep their own heads.
                    acc[0] = NEG
                    for _u in T.unroll(8):
                        if (tid % 16) * 8 + _u < iv[0]:
                            acc[0] = T.max(acc[0], T.Cast("float32", ps[tid // 16, (tid % 16) * 8 + _u]))
                    for _d in T.unroll(4):
                        acc[0] = T.max(acc[0], T.shfl_xor(acc[0], T.shift_left(1, _d)))
                    fv[0] = T.max(sml[16 + tid // 16], acc[0])
                    fv[2] = T.exp(sml[16 + tid // 16] - fv[0])
                    # a position past the end of the context gets a zero, which keeps it
                    # out of the sum and out of the product that follows
                    acc[0] = 0.0
                    for _u in T.unroll(8):
                        fv[1] = T.if_then_else((tid % 16) * 8 + _u < iv[0], T.exp(T.Cast("float32", ps[tid // 16, (tid % 16) * 8 + _u]) - fv[0]), 0.0)
                        ps[tid // 16, (tid % 16) * 8 + _u] = bf(fv[1])
                        acc[0] += fv[1]
                    for _d in T.unroll(4):
                        acc[0] += T.shfl_xor(acc[0], T.shift_left(1, _d))
                    if tid % 16 == 0:
                        sml[48 + tid // 16] = sml[48 + tid // 16] * fv[2] + acc[0]
                        sml[16 + tid // 16] = fv[0]
                        sml[112 + tid // 16] = fv[2]
                    T.sync_threads()
                    # rescale what the earlier blocks left, then add this block's share
                    for _i, _j in T.Parallel(16, 128):
                        of1[_i, _j] = of1[_i, _j] * sml[112 + _i]
                    T.gemm(ps, vs, of1)
                # the stripe's state: 32 context vectors and their (max, sum)
                T.copy(of0, fs2[0:16, :])
                T.copy(of1, fs2[16:32, :])
                T.sync_threads()
                for _i in T.unroll(16):
                    _j = _i * 256 + tid
                    scratch[S_ATT + (cta * 32 + _j // 128) * 130 + _j % 128] = fs[_j]
                if tid < 32:
                    scratch[S_ATT + (cta * 32 + tid) * 130 + 128] = sml[tid]
                    scratch[S_ATT + (cta * 32 + tid) * 130 + 129] = sml[32 + tid]
                T.sync_grid()
                # merge the stripes: one query head per CTA, over the stripes that exist
                _nact = T.max(T.min(T.ceildiv(_tot, _cb), 132), 1)
                if cta < 32:
                    if tid == 0:
                        acc[0] = NEG
                        for _c in T.serial(_nact):
                            acc[0] = T.max(acc[0], scratch[S_ATT + (_c * 32 + cta) * 130 + 128])
                        sml[MAXSLOT] = acc[0]
                    T.sync_threads()
                    if tid < 129:
                        acc[0] = 0.0
                        for _c in T.serial(_nact):
                            acc[0] += T.exp(scratch[S_ATT + (_c * 32 + cta) * 130 + 128] - sml[MAXSLOT]) * scratch[S_ATT + (_c * 32 + cta) * 130 + T.if_then_else(tid < 128, tid, 129)]
                        red[tid] = acc[0]
                    T.sync_threads()
                    if tid < 128:
                        scratch[S_CTX + cta * 128 + tid] = bf(red[tid] / red[128])
                T.sync_grid()
                for _i in T.unroll(16):
                    _j = _i * 256 + tid
                    out[_j] = bf(scratch[S_CTX + _j])
    return attn


class AttnRunner:
    """What the standalone attention keeps between calls."""

    _cache = {}

    @classmethod
    def get(cls, arm, device):
        key = (arm, str(device))
        if key not in cls._cache:
            cls._cache[key] = (build_attn(arm),
                               torch.zeros(SCRATCH, dtype=torch.float32, device=device),
                               torch.zeros(NPTR, dtype=torch.int64, device=device),
                               torch.zeros(2, dtype=torch.int32, device=device),
                               torch.zeros(QP, dtype=torch.bfloat16, device=device))
        return cls._cache[key]


def run_attn(arm, qg, k_cache, v_cache, k_tail, v_tail):
    """One decode step of full attention, by the named placement.

    `arm` is "head" or "context"; "dispatch" reads the crossover the semantics
    states off the whole-block context length, which is the number the mega
    step's own branch is on.
    """
    ctx_full, ctx_tail = k_cache.shape[1], k_tail.shape[1]
    if arm == "dispatch":
        arm = "head" if ctx_full < HSPLIT else "context"
    kernel, scratch, ptrs, meta, out = AttnRunner.get(arm, qg.device)
    ptrs[P_KC] = k_cache.data_ptr()
    ptrs[P_VC] = v_cache.data_ptr()
    ptrs[P_KT] = k_tail.data_ptr()
    ptrs[P_VT] = v_tail.data_ptr()
    meta[0], meta[1] = ctx_full, ctx_tail
    kernel(qg.reshape(-1), ptrs, meta, scratch, out)
    return out.reshape(1, QP)
